#!/usr/bin/env node
import { promises as fs } from 'node:fs';
import path from 'node:path';

const [, , rawName, rawOutputDir] = process.argv;

function usage() {
  console.log('Usage: pnpm run plugin:new <plugin-name> [output-dir]');
  console.log('Example: pnpm run plugin:new markdown-lint ./plugins');
}

function sanitizePluginName(input) {
  return input
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

function toPascalCase(input) {
  return input
    .split('-')
    .filter(Boolean)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join('');
}

async function exists(target) {
  try {
    await fs.access(target);
    return true;
  } catch {
    return false;
  }
}

async function writeFile(targetPath, content) {
  await fs.mkdir(path.dirname(targetPath), { recursive: true });
  await fs.writeFile(targetPath, content, 'utf8');
}

async function main() {
  if (!rawName) {
    usage();
    process.exit(1);
  }

  const pluginName = sanitizePluginName(rawName);

  if (!pluginName) {
    console.error('[plugin:new] Invalid plugin name. Use letters/numbers/hyphens only.');
    process.exit(1);
  }

  const outputRoot = rawOutputDir
    ? path.resolve(process.cwd(), rawOutputDir)
    : path.resolve(process.cwd(), 'plugins');
  const pluginDir = path.join(outputRoot, pluginName);

  if (await exists(pluginDir)) {
    console.error(`[plugin:new] Target directory already exists: ${pluginDir}`);
    process.exit(1);
  }

  const pascalName = toPascalCase(pluginName);
  const factoryName = `create${pascalName}Plugin`;

  const packageJson = JSON.stringify(
    {
      name: `moondown-plugin-${pluginName}`,
      version: '0.1.0',
      description: `Moondown plugin: ${pluginName}`,
      type: 'module',
      main: './dist/index.js',
      types: './dist/index.d.ts',
      exports: {
        '.': {
          import: './dist/index.js',
          types: './dist/index.d.ts',
        },
      },
      files: ['dist', 'README.md'],
      scripts: {
        build: 'tsc -p tsconfig.json',
        clean: 'rm -rf dist',
      },
      peerDependencies: {
        moondown: '^0.1.0',
      },
      dependencies: {
        '@codemirror/view': '^6.38.6',
      },
      devDependencies: {
        typescript: '^5.7.2',
      },
      keywords: ['moondown', 'plugin', pluginName],
      license: 'Apache-2.0',
    },
    null,
    2
  );

  const tsconfig = `{
  "compilerOptions": {
    "target": "ES2020",
    "module": "ESNext",
    "moduleResolution": "Bundler",
    "strict": true,
    "declaration": true,
    "outDir": "dist",
    "skipLibCheck": true
  },
  "include": ["src/**/*.ts"]
}
`;

  const srcIndex = `import { EditorView } from '@codemirror/view';
import { defineMoondownPlugin } from 'moondown';

export interface ${pascalName}PluginOptions {
  debug?: boolean;
  enableSlashCommand?: boolean;
}

export function ${factoryName}(options: ${pascalName}PluginOptions = {}) {
  return defineMoondownPlugin({
    name: '${pluginName}',
    slashCommands: options.enableSlashCommand === false
      ? []
      : [
          {
            id: '${pluginName}.insertTemplate',
            title: 'Insert ${pascalName} Template',
            icon: 'puzzle',
            keywords: ['template'],
            execute(view) {
              const pos = view.state.selection.main.from;
              view.dispatch({
                changes: {
                  from: pos,
                  insert: '# ${pascalName} Template\\n\\n- item 1\\n- item 2\\n',
                },
              });
            },
          },
        ],
    setup() {
      return EditorView.updateListener.of((update) => {
        if (!update.docChanged || !options.debug) {
          return;
        }

        console.log('[${pluginName}] doc length =', update.state.doc.length);
      });
    },
    onViewCreated({ view }) {
      if (options.debug) {
        console.log('[${pluginName}] mounted');
      }

      view.dom.dataset['${pluginName.replace(/-/g, '')}Plugin'] = 'enabled';
    },
    onDestroy() {
      if (options.debug) {
        console.log('[${pluginName}] destroyed');
      }
    },
  });
}

export default ${factoryName};
`;

  const readme = `# moondown-plugin-${pluginName}

Moondown plugin scaffold generated by \`pnpm run plugin:new\`.

## Install

\`\`\`bash
pnpm add moondown @codemirror/view
\`\`\`

## Build

\`\`\`bash
pnpm install
pnpm run build
\`\`\`

## Usage

\`\`\`ts
import Moondown from 'moondown';
import { ${factoryName} } from 'moondown-plugin-${pluginName}';

const editor = new Moondown(container, '# Hello', {
  plugins: [${factoryName}({ debug: true })],
});
\`\`\`
`;

  await writeFile(path.join(pluginDir, 'package.json'), `${packageJson}\n`);
  await writeFile(path.join(pluginDir, 'tsconfig.json'), tsconfig);
  await writeFile(path.join(pluginDir, 'src/index.ts'), srcIndex);
  await writeFile(path.join(pluginDir, 'README.md'), readme);

  console.log(`[plugin:new] Scaffold created at: ${pluginDir}`);
  console.log('[plugin:new] Next steps:');
  console.log(`  1. cd ${pluginDir}`);
  console.log('  2. pnpm install');
  console.log('  3. pnpm run build');
}

main().catch((error) => {
  console.error('[plugin:new] Failed to create scaffold:', error);
  process.exit(1);
});
