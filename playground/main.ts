let readOnly = false;
let accent: AccentName = 'blue';
let editorRef: Moondown | null = null;
let aiSettings: PlaygroundAISettings = getDefaultAISettings();

function isAccentName(value: string | undefined): value is AccentName {
  return !!value && value in ACCENT_PRESETS;
}

function applyAccent(nextAccent: AccentName): void {
  accent = nextAccent;
  const preset = ACCENT_PRESETS[nextAccent];
  const rootStyle = document.documentElement.style;
  rootStyle.setProperty('--color-primary-hsl', preset.hsl);
  rootStyle.setProperty('--color-primary-light-hsl', preset.lightHsl);
  rootStyle.setProperty('--color-primary-dark-hsl', preset.darkHsl);
  rootStyle.setProperty('--accent-label', preset.label);
}

function writeAISettingsToControls(settings: PlaygroundAISettings): void {
  aiModeSelect.value = settings.mode;
  localeInput.value = settings.locale;
  aiChunkSizeInput.value = String(settings.mockChunkSize);
  aiDelayMsInput.value = String(settings.mockDelayMs);
  aiEndpointInput.value = settings.endpoint;
  aiAuthTokenInput.value = settings.authToken;
}

function syncAIControls(): void {
  const realMode = aiModeSelect.value === 'real';
  aiChunkSizeInput.disabled = realMode;
  aiDelayMsInput.disabled = realMode;
  aiEndpointInput.disabled = !realMode;
  aiAuthTokenInput.disabled = !realMode;
}

function readAISettingsFromControls(previous: PlaygroundAISettings): PlaygroundAISettings {
  const mode = aiModeSelect.value === 'real' ? 'real' : 'mock';
  return {
    mode,
    locale: normalizeLocale(localeInput.value),
    mockChunkSize: parsePositiveInt(aiChunkSizeInput.value, previous.mockChunkSize),
    mockDelayMs: parsePositiveInt(aiDelayMsInput.value, previous.mockDelayMs),
    endpoint: normalizeEndpoint(aiEndpointInput.value),
    authToken: aiAuthTokenInput.value.trim(),
  };
}

