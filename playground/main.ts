function parseTag(content: string, tag: string): string {
  const match = content.match(new RegExp(`<${tag}>\\s*([\\s\\S]*?)\\s*</${tag}>`, 'i'));
  return (match?.[1] || '').trim();
}

function normalizeLocale(locale: string): string {
  const normalized = locale.trim();
  return normalized.length > 0 ? normalized : 'en';
}

function normalizeEndpoint(endpoint: string): string {
  const normalized = endpoint.trim();
  return normalized.length > 0 ? normalized : '/__ai_stream';
}

function parsePositiveInt(value: string, fallback: number): number {
  const parsed = Number.parseInt(value, 10);
  if (!Number.isFinite(parsed) || parsed < 1) {
    return fallback;
  }
  return parsed;
}

function toStream(
  text: string,
  signal: AbortSignal,
  chunkSize: number,
  delayMs: number
): ReadableStream<string> {
  return new ReadableStream<string>({
    start(controller) {
      let index = 0;
      const timer = window.setInterval(() => {
        if (signal.aborted) {
          window.clearInterval(timer);
          controller.error(new DOMException('Aborted', 'AbortError'));
          return;
        }

        if (index >= text.length) {
          window.clearInterval(timer);
          controller.close();
          return;
        }

        const chunk = text.slice(index, index + chunkSize);
        index += chunkSize;
        controller.enqueue(chunk);
      }, delayMs);

      signal.addEventListener('abort', () => {
        window.clearInterval(timer);
        controller.error(new DOMException('Aborted', 'AbortError'));
      });
    }
  });
}

function createMockAIStream(settings: PlaygroundAISettings): AIStreamHandler {
  const chunkSize = settings.mockChunkSize;
  const delayMs = settings.mockDelayMs;

  return async (_systemPrompt, userPrompt, signal) => {
    if (userPrompt.includes('<text_before_cursor>')) {
      const output = '\n\nThis continuation is generated by the local playground AI mock.';
      return toStream(output, signal, chunkSize, delayMs);
    }

    const sourceText = parseTag(userPrompt, 'source_text');
    const instruction = parseTag(userPrompt, 'user_instruction');
    const normalized = sourceText
      .split('\n')
      .map((line) => line.trimEnd())
      .join('\n')
      .replace(/[ ]{2,}/g, ' ')
      .trim();

    const response = instruction
      ? `${normalized}\n\n(Polished with instruction: ${instruction})`
      : `${normalized}\n\n(Polished by playground mock AI)`;

    return toStream(response, signal, chunkSize, delayMs);
  };
}

function createRealAIStream(settings: PlaygroundAISettings): AIStreamHandler {
  const endpoint = normalizeEndpoint(settings.endpoint);
  const authToken = settings.authToken.trim();

  return async (systemPrompt, userPrompt, signal) => {
    const headers: Record<string, string> = {
      'Content-Type': 'application/json',
    };
    if (authToken.length > 0) {
      headers.Authorization = `Bearer ${authToken}`;
    }

    const response = await fetch(endpoint, {
      method: 'POST',
      headers,
      body: JSON.stringify({ systemPrompt, userPrompt }),
      signal,
    });

    if (!response.ok || !response.body) {
      const text = await response.text().catch(() => '');
      throw new Error(`AI request failed: ${response.status} ${text}`);
    }

    return new ReadableStream<string>({
      async start(controller) {
        const reader = response.body!.getReader();
        const decoder = new TextDecoder();
        while (true) {
          const { done, value } = await reader.read();
          if (done) break;
          controller.enqueue(decoder.decode(value, { stream: true }));
        }
        controller.close();
      },
      cancel() {
        try {
          response.body?.cancel();
        } catch {
          // ignore
        }
      },
    });
  };
}

function createAIHandler(settings: PlaygroundAISettings): AIStreamHandler {
  if (settings.mode === 'real') {
    return createRealAIStream(settings);
  }
  return createMockAIStream(settings);
}

