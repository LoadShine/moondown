function syncStatus(): void {
  themeState.textContent = theme;
  syntaxState.textContent = syntaxHiding ? 'on' : 'off';
  readonlyState.textContent = readOnly ? 'on' : 'off';
  accentState.textContent = ACCENT_PRESETS[accent].label;
  aiModeState.textContent = aiSettings.mode;
  localeState.textContent = aiSettings.locale;
  aiEndpointState.textContent = aiSettings.mode === 'real' ? aiSettings.endpoint : '(mock)';
  setPressedState();
  document.documentElement.dataset.theme = theme;
  document.documentElement.dataset.syntaxHiding = syntaxHiding ? 'on' : 'off';
  document.documentElement.dataset.readonly = readOnly ? 'on' : 'off';
  document.documentElement.dataset.accent = accent;
  for (const button of accentButtons) {
    const isActive = button.dataset.accent === accent;
    button.classList.toggle('is-selected', isActive);
    button.setAttribute('aria-pressed', String(isActive));
  }
  (window as { __MOONDOWN_PLAYGROUND_AI_SETTINGS__?: PlaygroundAISettings }).__MOONDOWN_PLAYGROUND_AI_SETTINGS__ = {
    ...aiSettings,
  };
}

function setPressedState(): void {
  toggleThemeInput.checked = theme === 'dark';
  toggleSyntaxInput.checked = syntaxHiding;
  toggleReadonlyInput.checked = readOnly;
}

function applyAISettings(nextSettings: PlaygroundAISettings): void {
  aiSettings = nextSettings;
  writeAISettingsToControls(aiSettings);
  syncAIControls();
  editor.setLocale(aiSettings.locale);
  editor.setAIStreamHandler(createAIHandler(aiSettings));
  syncStatus();
}

